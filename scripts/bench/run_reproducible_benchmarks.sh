#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
BUILD_DIR="${BUILD_DIR:-$ROOT_DIR/build}"
OPS_DIRECT="${OPS_DIRECT:-20000}"
OPS_SERVER="${OPS_SERVER:-5000}"
PORT="${PORT:-4242}"

TIMESTAMP="$(date -u +%Y%m%dT%H%M%SZ)"
SHORT_SHA="$(git -C "$ROOT_DIR" rev-parse --short HEAD)"
OUT_DIR="${OUT_DIR:-$ROOT_DIR/bench/artifacts/runs/${TIMESTAMP}-${SHORT_SHA}}"

mkdir -p "$OUT_DIR"

meta_file="$OUT_DIR/metadata.txt"
{
  echo "timestamp_utc=$TIMESTAMP"
  echo "git_commit=$(git -C "$ROOT_DIR" rev-parse HEAD)"
  echo "git_branch=$(git -C "$ROOT_DIR" rev-parse --abbrev-ref HEAD)"
  if git -C "$ROOT_DIR" diff --quiet && git -C "$ROOT_DIR" diff --cached --quiet; then
    echo "git_dirty=false"
  else
    echo "git_dirty=true"
  fi
  echo "ops_direct=$OPS_DIRECT"
  echo "ops_server=$OPS_SERVER"
  echo "port=$PORT"
  echo "build_dir=$BUILD_DIR"
  echo "cmake_flags=-DCHUNKDB_BUILD_TESTS=ON -DCHUNKDB_WITH_TLS=OFF"
} > "$meta_file"

if command -v uname >/dev/null 2>&1; then
  uname -a > "$OUT_DIR/system_uname.txt"
fi

if command -v sw_vers >/dev/null 2>&1; then
  sw_vers > "$OUT_DIR/system_sw_vers.txt"
fi

if command -v lscpu >/dev/null 2>&1; then
  lscpu > "$OUT_DIR/system_lscpu.txt"
fi

if command -v sysctl >/dev/null 2>&1; then
  sysctl -n machdep.cpu.brand_string > "$OUT_DIR/system_cpu_brand.txt" 2>/dev/null || true
fi

if command -v c++ >/dev/null 2>&1; then
  c++ --version > "$OUT_DIR/compiler_version.txt" 2>&1 || true
fi

if command -v cmake >/dev/null 2>&1; then
  cmake --version > "$OUT_DIR/cmake_version.txt" 2>&1 || true
fi

cmake -S "$ROOT_DIR" -B "$BUILD_DIR" -DCHUNKDB_BUILD_TESTS=ON -DCHUNKDB_WITH_TLS=OFF \
  > "$OUT_DIR/cmake_configure.log" 2>&1

cmake --build "$BUILD_DIR" --parallel > "$OUT_DIR/cmake_build.log" 2>&1

ctest --test-dir "$BUILD_DIR" --output-on-failure > "$OUT_DIR/ctest.log" 2>&1

"$BUILD_DIR/chunkdb_bench" --ops "$OPS_DIRECT" > "$OUT_DIR/chunkdb_bench.txt" 2>&1
"$BUILD_DIR/chunkdb_server_bench" \
  --server-mode spawn \
  --host 127.0.0.1 \
  --port "$PORT" \
  --clients 50 \
  --pipeline 1 \
  --requests "$OPS_SERVER" \
  --tests ping,info,set,get,chunk,chunkbin,mixed \
  --keyspace 512 \
  --seed 1337 \
  > "$OUT_DIR/chunkdb_server_bench.txt" 2>&1

cat > "$OUT_DIR/README.txt" <<EOF
Reproducible benchmark artifact bundle

Files:
- metadata.txt: run parameters and git revision
- system_*.txt: host metadata
- cmake_configure.log / cmake_build.log / ctest.log: build and test logs
- chunkdb_bench.txt: direct API benchmark output
- chunkdb_server_bench.txt: server-path benchmark output

Generated by: scripts/bench/run_reproducible_benchmarks.sh
EOF

echo "artifact_dir=$OUT_DIR"
